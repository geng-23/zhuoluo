/// 从快速添加输入中提取任务标题（去掉已识别的时间词）
///
/// 按解析器语义整体切除（此前逐词 replaceAll 会把"每周五跑步"
/// 拆成"五跑步"、"每时每刻"误删"每"、"3点到4点交报告"残留"到"）。
/// 任务页与日历页共用同一实现（此前两份重复且行为不一致）。
String extractTaskTitle(String input) {
  // 数字/中文数字（"五点"、"每一周"、"每两个月"等中文数字时间词同样切除）
  const n2 = r'(?:[0-9]{1,2}|[零一二三四五六七八九十两]{1,3})';
  const n = r'(?:[0-9]+|[零一二三四五六七八九十两]+)';
  var title = input;
  final patterns = [
    // 下个月底需整体切除（先于"月底"，否则残留"下个月"）
    RegExp(r'下个月?月底|下个月?底'),
    RegExp(r'大后天|后天|明天|今天|昨天|月底'),
    RegExp('下个月?$n2[日号]?'),
    // N月N日须先于"N号"（否则"八月十日"先被切掉"十日"残留"八月"）
    RegExp('$n2月$n2[日号]?'),
    RegExp('(?:这个月)?$n2[日号]'),
    // 仅显式"后"才算相对日期（与解析器一致，裸"N天"保留）
    RegExp('$n天(?:之)?后'),
    RegExp(r'每周[一二三四五六日天]'),
    // 每N周X 整体切除（先于"每N[天周月]"，否则残留星期字）
    RegExp('每$n周[一二三四五六日天]'),
    RegExp('每$n个?[天周月]'),
    RegExp('每月$n号?'),
    RegExp(r'[下本这]?周[一二三四五六日天]'),
    RegExp(r'\d{1,4}[-/]\d{1,2}[-/]?\d{0,2}'),
    // 时间段整体："下午3点到4点" / "晚上11点到1点" / "下午三点到五点"
    RegExp(
      '(?:上午|下午|晚上|傍晚|中午|早上|早晨|凌晨|下)?$n2[点时]'
      '(?:$n2分?|半)?'
      '(?:到(?:上午|下午|晚上|傍晚|中午|早上|早晨|凌晨|下)?$n2[点时](?:$n2分?|半)?)?',
    ),
    // 孤立结束时间（如"9点 到 10点"带空格时）
    RegExp(
      '[到至](?:上午|下午|晚上|傍晚|中午|早上|早晨|凌晨|下)?$n2[点时](?:$n2分?|半)?',
    ),
    RegExp(r'\d{1,2}:\d{2}'),
  ];
  for (final p in patterns) {
    title = title.replaceAll(p, '');
  }
  title = title
      .replaceAll(RegExp(r'[，。,.、\s]+'), ' ')
      .trim();
  return title.isEmpty ? input.trim() : title;
}
